#!/usr/bin/env python3
"""Turns a file into a C source with its bytes (Python 3 standard library only).

Used by build.sh to embed the neutral theme in the executable, so the launcher has a look even
before it reaches the server:

    python3 tools/embed.py examples/theme-neutral/theme.json build/gen/theme_neutral.c theme_neutral

produces

    const unsigned char theme_neutral[] = {0x7b, ...};
    const unsigned int theme_neutral_size = 1234;

The array is not NUL-terminated (the JSON parser takes a length). The output is only rewritten
when its content changes, so incremental builds stay incremental.

Usage: tools/embed.py INPUT OUTPUT.c SYMBOL
"""

import re
import sys
from pathlib import Path


def render(data: bytes, symbol: str, source: str) -> str:
    lines = [
        f"/* Generated by tools/embed.py from {source}. Do not edit. */",
        f"const unsigned char {symbol}[] = {{",
    ]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    if not data:
        lines.append("    0")  # C forbids empty initialisers; size stays 0
    lines.append("};")
    lines.append(f"const unsigned int {symbol}_size = {len(data)}u;")
    return "\n".join(lines) + "\n"


def main(argv) -> int:
    if len(argv) != 4 or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", argv[3]):
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    source, output, symbol = Path(argv[1]), Path(argv[2]), argv[3]
    text = render(source.read_bytes(), symbol, source.name)
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text(encoding="ascii") != text:
        output.write_text(text, encoding="ascii")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
